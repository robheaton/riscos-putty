#!/usr/bin/env python3
"""Test the console tools' keyboard prompts in RPCEmu without typing at the emulator.

The tools read passphrases, host key questions and the psftp prompt from the keyboard
(OS_ReadC / OS_Byte 129).  Nothing can be typed at the emulator without its VNC password, and
neither OS_Byte 138 (insert into the keyboard buffer) nor *Exec reaches INKEY or OS_ReadC in the
test harness (both were tried, and a program waiting for a key then hangs the harness), so the
tools have a test hook: with the system variable PuTTY$KeyFile naming a file, they read their
keystrokes from it (ro_test_key in util.c).  That exercises everything the tools do with the
keys - prompts, the line editor, history, the answers to questions - but not the two OS calls
themselves, which plink has long used.  Each case is "Set PuTTY$KeyFile <file>; tool".  The
end of the file counts as Escape, so a prompt nobody answers ends instead of waiting.

    tools/kbtest.py setup     make the files, write the guest scripts, start two test servers
                              (A on 2224 as in sftptest.py, B on 2225 with another host key)
    (then in RPCEmu:  Obey HostFS::HostFS.$.PuttyDev.kb.kb1, kb2)
    tools/kbtest.py swap      restart B with a third host key (for the "key changed" case)
    (then:  Obey HostFS::HostFS.$.PuttyDev.kb.kb3)
    tools/kbtest.py check     compare the results with what should have happened
    tools/kbtest.py stop      stop the servers
"""
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOSTBIN = os.path.join(ROOT, "build", "host")
PUTTYGEN = os.path.join(HOSTBIN, "puttygen")
HOSTFS = os.environ.get("RPCEMU_HOSTFS", os.path.expanduser("~/RPCEmu/machines/RISC OS 5/hostfs"))
KB = os.path.join(HOSTFS, "PuttyDev", "kb")
GUEST = "HostFS::HostFS.$.PuttyDev.kb"
T = os.path.join(ROOT, "build", "test")
PIDS = os.path.join(T, "kb.pids")
USERKEY = "HostFS::HostFS.$.PuttyDev.ClientKey"
XIN = os.path.join(T, "xfer", "in")                 # sftptest.py's files, for the pscp case

PW = "secret one"
NEWPW = "new pass"


def host(*args, check=True):
    r = subprocess.run([PUTTYGEN, *args], capture_output=True, text=True)
    if check and r.returncode:
        raise RuntimeError("host puttygen %s: %s" % (" ".join(args), r.stderr.strip()))
    return r


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb" if isinstance(data, bytes) else "w") as f:
        f.write(data)


def fingerprint(path):
    return host(path, "-l").stdout.split()[2]


def hostkey(n):
    path = os.path.join(T, "hostkey%d.ppk" % n)
    if not os.path.exists(path):
        host("-t", "ed25519", "-o", path, "--new-passphrase", "/dev/null")
    return path


def start_server(port, hostkey_path, extra=()):
    home = os.path.join(T, "home")
    os.makedirs(home, exist_ok=True)
    env = {"HOME": home, "PATH": "/usr/bin:/bin", "SHELL": "/bin/sh", "PS1": "$ "}
    p = subprocess.Popen([os.path.join(HOSTBIN, "uppity"), "--listen", str(port), "--hostkey", hostkey_path,
                          "--userkey", os.path.join(T, "client.pub"), "--sessiondir", home, *extra],
                         env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    return p.pid


def read_pids():
    try:
        return json.load(open(PIDS))
    except (OSError, ValueError):
        return {}


def kill_server(name):
    pids = read_pids()
    pid = pids.pop(name, None)
    if pid:
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass
    json.dump(pids, open(PIDS, "w"))


def server(name, port, n, extra=()):
    kill_server(name)
    time.sleep(0.3)
    pid = start_server(port, hostkey(n), extra)
    pids = read_pids()
    pids[name] = pid
    json.dump(pids, open(PIDS, "w"))


# ---------------------------------------------------------------------------------------
class Script:
    def __init__(self, name):
        self.name = name
        self.log = "{ >> %s.log }" % GUEST
        self.lines = ["| generated by tools/kbtest.py - do not edit", "Set Sys$RCLimit 255",
                      "Set PuTTY$Timeout 8", "Set PuTTY$NoEntropyWarning 1",
                      "Set Run$Path HostFS::HostFS.$.PuttyDev.,<Run$Path>", "Dir " + GUEST]

    def case(self, name, keys, command):
        """keys (a str, with real control characters) are what the tool will find typed."""
        write(os.path.join(KB, "keys", name), keys.encode("latin-1"))
        self.lines += ["Echo === %s %s" % (name, self.log),
                       "Set PuTTY$KeyFile %s.keys.%s" % (GUEST, name),
                       "%s %s" % (command, self.log), "Echo rc=<Sys$ReturnCode> %s" % self.log]

    def raw(self, line):
        self.lines.append(line)

    def save(self):
        self.lines.append("Echo script %s finished %s" % (self.name, self.log))
        write(os.path.join(KB, self.name + ",feb"), "\n".join(self.lines) + "\n")


def build_scripts():
    fp1 = fingerprint(os.path.join(T, "hostkey.ppk"))
    k1, k2, k3 = Script("kb1"), Script("kb2"), Script("kb3")

    # ---- puttygen -------------------------------------------------------------------
    for n in range(1, 13):
        k1.raw("X Delete k%d" % n)
    k1.raw("X Delete k6txt")
    k1.case("gen-typed", "%s\r%s\r" % (PW, PW), "puttygen -t ed25519 -o k1")
    k1.case("gen-mismatch", "abc\rabd\r", "puttygen -t ed25519 -o k2")
    k1.case("gen-no-passphrase", "\r\r", "puttygen -t ed25519 -o k3")
    k1.case("gen-backspace", "wrong\b\b\b\b\bright\rright\r", "puttygen -t ed25519 -o k4")
    k1.case("gen-ctrl-u", "junk\x15good\rgood\r", "puttygen -t ed25519 -o k5")
    k1.case("load-right", "%s\r" % PW, "puttygen k1 -O text -o k6txt")
    k1.case("load-wrong", "nope\r", "puttygen k1 -O text")
    k1.raw("Copy k1 k8 ~C~V")
    k1.case("change-passphrase", "%s\r%s\r%s\r" % (PW, NEWPW, NEWPW), "puttygen k8 -P")
    k1.case("convert-openssh", "alpha passphrase one\r", "puttygen in.osshEdPw -o k9 --new-passphrase in.empty")
    k1.case("timeout", "", "puttygen k1 -O text")                     # nothing typed: PuTTY$Timeout gives up

    # ---- psftp at its prompt, and the password prompts ---------------------------------
    k2.raw("X Delete <Choices$Write>.PuTTY.SSHHostKeys")
    common = "-i %s -l tester -P 2224 -hostkey %s" % (USERKEY, fp1)
    k2.case("psftp-edit-and-recall", "pwx\bd\rlpwd\r\x8b\rquit\r", "psftp %s 10.10.10.2" % common)
    k2.case("psftp-history-two-back", "pwd\rlpwd\r\x8b\x8b\r\x04", "psftp %s 10.10.10.2" % common)
    k2.case("psftp-ctrl-d", "\x04", "psftp %s 10.10.10.2" % common)
    k2.case("psftp-password", "weasel\rpwd\rquit\r", "psftp -l tester -P 2224 -hostkey %s 10.10.10.2" % fp1)
    k2.case("plink-password", "weasel\r", "plink -l tester -P 2224 -hostkey %s 10.10.10.2 echo typed-password-ok" % fp1)
    k2.case("plink-wrong-password", "wrong\r", "plink -l tester -P 2224 -hostkey %s 10.10.10.2 echo not-reached" % fp1)
    k2.case("pscp-password", "weasel\r",
            "pscp -l tester -P 2224 -hostkey %s 10.10.10.2:%s/hello.txt %s.fromscp.hello/txt" % (fp1, XIN, GUEST))
    # first connection to server B: the host key question; then it is cached
    k2.case("hostkey-first-time", "y\rquit\r", "psftp -i %s -l tester -P 2225 10.10.10.2" % USERKEY)
    k2.case("hostkey-cached", "quit\r", "psftp -i %s -l tester -P 2225 10.10.10.2" % USERKEY)
    k2.case("plink-kbdint", "stoat\rweasel\r",
            "plink -l tester -P 2226 -hostkey %s 10.10.10.2 echo typed-kbdint-ok" % fp1)
    k2.case("hostkey-once", "n\rquit\r", "psftp -i %s -l tester -P 2226 10.10.10.2" % USERKEY)
    k2.case("hostkey-once-again", "n\rquit\r", "psftp -i %s -l tester -P 2226 10.10.10.2" % USERKEY)
    k2.case("hostkey-refused", "\r", "psftp -i %s -l tester -P 2226 10.10.10.2" % USERKEY)

    # ---- after "swap": server B has a different key under the same name ----------------
    k3.case("hostkey-changed-cancel", "\r", "psftp -i %s -l tester -P 2225 10.10.10.2" % USERKEY)
    k3.case("hostkey-changed-update", "y\rquit\r", "psftp -i %s -l tester -P 2225 10.10.10.2" % USERKEY)
    k3.case("hostkey-updated-cached", "quit\r", "psftp -i %s -l tester -P 2225 10.10.10.2" % USERKEY)
    for s in (k1, k2, k3):
        s.save()


def setup():
    shutil.rmtree(KB, ignore_errors=True)
    os.makedirs(KB)
    write(os.path.join(KB, "log"), "")
    os.makedirs(os.path.join(KB, "fromscp"))
    os.makedirs(os.path.join(KB, "keys"))
    inputs = os.path.join(HOSTFS, "PuttyDev", "kg", "in")
    os.makedirs(os.path.join(KB, "in"))
    write(os.path.join(KB, "in", "empty"), "\n")
    src = os.path.join(inputs, "osshEdPw")
    if not os.path.exists(src):
        sys.exit("run tools/keytest.py setup first (it makes the OpenSSH key this uses)")
    shutil.copy(src, os.path.join(KB, "in", "osshEdPw"))
    if not os.path.isdir(XIN):
        sys.exit("run tools/sftptest.py setup first (it makes the files pscp fetches)")
    build_scripts()
    # A uses the same host key as sftptest.py (build/test/hostkey.ppk)
    kill_server("A")
    pids = read_pids()
    pids["A"] = start_server(2224, os.path.join(T, "hostkey.ppk"), ["--deny-auth", "kbdint"])   # password, not kbdint
    json.dump(pids, open(PIDS, "w"))
    server("B", 2225, 2)
    kill_server("C")
    pids = read_pids()
    pids["C"] = start_server(2226, os.path.join(T, "hostkey.ppk"))          # keyboard-interactive allowed
    json.dump(pids, open(PIDS, "w"))
    print("scripts kb1 kb2 kb3 in %s; servers A (2224, passwords), B (2225) and C (2226, kbdint) running" % KB)
    print("in RPCEmu: Obey %s.kb1, then kb2; then  tools/kbtest.py swap  and  Obey %s.kb3; then check" % (GUEST, GUEST))


# ---------------------------------------------------------------------------------------
results = []


def report(name, ok, why=""):
    ok = bool(ok)
    results.append(ok)
    print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, "" if ok else ": " + why))


def parse_log():
    text = open(os.path.join(KB, "log"), "rb").read().decode("latin-1").replace("\r", "")
    cases = {}
    for chunk in re.split(r"^=== ", text, flags=re.M)[1:]:
        lines = chunk.split("\n")
        name = lines[0].strip()
        body = "\n".join(lines[1:])
        rcs = re.findall(r"rc=(\d+) *\n", chunk)
        cases[name] = (re.sub(r"rc=\d+ *$", "", body.rstrip()).rstrip(), int(rcs[-1]) if rcs else None)
    return cases


def exists(name):
    for suffix in ("", ",fff", ",ffd"):
        if os.path.exists(os.path.join(KB, name + suffix)):
            return os.path.join(KB, name + suffix)
    return None


def check():
    cases = parse_log()

    def case(name):
        if name not in cases:
            report(name, False, "the guest did not run it")
            return None
        return cases[name]

    pwfile = os.path.join(T, "kb-pw")

    def dump(path, pw):
        write(pwfile, pw + "\n")
        return host(path, "-O", "text", "--old-passphrase", pwfile, check=False)

    def loads(path, pw):
        return dump(path, pw).returncode == 0

    def encrypted(path):
        return "Encryption: aes256-cbc" in open(path, "rb").read(200).decode("latin-1")

    print("puttygen")
    c = case("gen-typed")
    p = exists("k1")
    report("passphrase typed twice makes an encrypted key", c and c[1] == 0 and p and encrypted(p) and loads(p, PW),
           "rc %s, file %s" % (c and c[1], p))
    c = case("gen-mismatch")
    report("passphrases that differ are refused and nothing is written",
           c and c[1] == 1 and "do not match" in c[0] and not exists("k2"), c and c[0][-120:])
    c = case("gen-no-passphrase")
    p = exists("k3")
    report("Return twice makes a key without a passphrase", c and c[1] == 0 and p and not encrypted(p), "")
    c = case("gen-backspace")
    p = exists("k4")
    report("Backspace edits the passphrase", c and c[1] == 0 and p and loads(p, "right"), c and c[0][-120:])
    c = case("gen-ctrl-u")
    p = exists("k5")
    report("Ctrl-U clears the line", c and c[1] == 0 and p and loads(p, "good"), c and c[0][-120:])
    c = case("load-right")
    txt = exists("k6txt")
    ref = dump(exists("k1"), PW).stdout if exists("k1") else None
    report("the right passphrase opens a key", c and c[1] == 0 and txt and open(txt).read() == ref, c and c[0][-120:])
    c = case("load-wrong")
    report("the wrong passphrase is refused", c and c[1] == 1 and "wrong passphrase" in c[0], c and c[0][-120:])
    c = case("change-passphrase")
    p = exists("k8")
    report("-P asks for old and new passphrases", c and c[1] == 0 and p and loads(p, NEWPW) and not loads(p, PW), c and c[0][-160:])
    c = case("convert-openssh")
    p = exists("k9")
    report("the passphrase of an OpenSSH key is typed", c and c[1] == 0 and p, c and c[0][-160:])
    c = case("timeout")
    report("an unanswered prompt gives up (PuTTY$Timeout)", c and c[1] == 1, c and (c[1], c[0][-120:]))

    print("psftp, plink, pscp")
    c = case("psftp-edit-and-recall")
    report("typed, edited and recalled commands run",
           c and c[1] == 0 and c[0].count("Remote directory is") == 1 and c[0].count("Current local directory is") == 2,
           c and c[0][-300:])
    c = case("psftp-history-two-back")
    report("Up twice recalls the command before last",
           c and c[0].count("Remote directory is") == 2 and c[0].count("Current local directory is") == 1, c and c[0][-300:])
    c = case("psftp-ctrl-d")
    report("Ctrl-D at the prompt ends psftp", c and c[1] == 0 and "psftp> " in c[0], c and c[0][-200:])
    c = case("psftp-password")
    report("psftp asks for a password", c and c[1] == 0 and "Remote directory is" in c[0], c and c[0][-300:])
    c = case("plink-password")
    report("plink asks for a password", c and c[1] == 0 and "typed-password-ok" in c[0], c and c[0][-300:])
    c = case("plink-wrong-password")
    # (an abort at a prompt counts as a clean exit in PuTTY, so the return code is 0 - see ssh_user_close)
    report("a wrong password is refused and the prompt comes again", c and "not-reached" not in c[0]
           and "ccess denied" in c[0] and c[0].count("password:") == 2, c and c[0][-300:])
    c = case("pscp-password")
    got = exists("fromscp/hello.txt") or exists("fromscp/hello")
    report("pscp asks for a password and fetches the file", c and c[1] == 0 and got, c and c[0][-300:])
    c = case("hostkey-first-time")
    report("an unknown host key is asked about, then the session goes on",
           c and c[1] == 0 and "not cached" in c[0] and "Remote working directory" in c[0], c and c[0][-400:])
    c = case("hostkey-cached")
    report("once accepted the key is remembered", c and c[1] == 0 and "not cached" not in c[0] and "Remote working directory" in c[0], c and c[0][-400:])
    c = case("plink-kbdint")
    report("keyboard-interactive: an echoing prompt and a silent one", c and c[1] == 0 and "typed-kbdint-ok" in c[0], c and c[0][-300:])
    c = case("hostkey-once")
    report("n connects once without storing the key", c and c[1] == 0 and "not cached" in c[0] and "Remote working directory" in c[0], c and c[0][-300:])
    c = case("hostkey-once-again")
    report("so the next connection asks again", c and c[1] == 0 and "not cached" in c[0], c and c[0][-300:])
    c = case("hostkey-refused")
    report("Return abandons the connection", c and c[1] != 0 and "Remote working directory" not in c[0], c and c[0][-400:])

    if "hostkey-changed-cancel" in cases:
        print("after the host key changed")
        c = case("hostkey-changed-cancel")
        report("a changed key gives the warning and Return cancels", c and c[1] != 0 and "POTENTIAL SECURITY BREACH" in c[0]
               and "Remote working directory" not in c[0], c and c[0][-500:])
        c = case("hostkey-changed-update")
        report("y updates the cache and the session goes on", c and c[1] == 0 and "Remote working directory" in c[0], c and c[0][-500:])
        c = case("hostkey-updated-cached")
        report("the updated key is remembered", c and c[1] == 0 and "POTENTIAL" not in c[0] and "Remote working directory" in c[0], c and c[0][-300:])
    else:
        print("(kb3, the changed host key cases, has not been run)")

    bad = results.count(False)
    print("\n%d checks, %d failed" % (len(results), bad))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) == 2 else None
    if cmd == "setup":
        setup()
    elif cmd == "swap":
        server("B", 2225, 3)
        print("server B now has host key 3")
    elif cmd == "stop":
        for n in ("A", "B", "C"):
            kill_server(n)
        print("stopped")
    elif cmd == "check":
        check()
    else:
        sys.exit(__doc__)
