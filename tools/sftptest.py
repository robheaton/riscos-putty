results = []


def report(name, ok, why=""):
    results.append(ok)
    print("  %-4s %s%s" % ("ok" if ok else "FAIL", name, "" if ok else ": " + why))


def hostfile(root, *names):
    """A file as HostFS shows it: the first of the names (with the ,xxx suffix it has) that exists."""
    for n in names:
        p = os.path.join(root, n)
        if os.path.exists(p):
            return p
    return None


def check_download(files):
    print("downloads (psftp)")
    down = os.path.join(SF, "down")

    def same(label, srcname, *candidates, suffix=None, expect_name=None):
        src = os.path.join(XIN, srcname)
        got = hostfile(down, *candidates)
        if not got:
            report(label, False, "not found as %s; have %s" % (candidates, sorted(os.listdir(down))))
            return
        if md5(got) != md5(src):
            report(label, False, "content differs")
            return
        base = os.path.basename(got)
        want_suffix = suffix or ""
        if want_suffix and not base.endswith(want_suffix):
            report(label, False, "filetype suffix %r expected, file is %s" % (want_suffix, base))
            return
        if not want_suffix and ("," in base[-4:]):
            report(label, False, "unexpected filetype suffix on %s (should be Text)" % base)
            return
        report(label, True)

    same("hello.txt -> hello/txt (Text from the extension)", "hello.txt", "hello.txt")
    same("data.bin -> bin extension unknown, looks like data (Data)", "data.bin", "data.bin,ffd", suffix=",ffd")
    same("pic.png -> PNG (&B60)", "pic.png", "pic.png,b60", suffix=",b60")
    same("notes,fff -> notes, typed by its suffix (Text)", "notes,fff", "notes")
    same("drawing,aff -> drawing, typed by its suffix (&AFF)", "drawing,aff", "drawing,aff", suffix=",aff")
    same("Makefile (no extension, looks like text)", "Makefile", "Makefile")
    same("archive.tar.gz (binary)", "archive.tar.gz", "archive.tar.gz,ffd", suffix=",ffd")
    same("empty.txt", "empty.txt", "empty.txt")
    same("name with $ and &", "weird$&name.txt", "weird__name.txt")
    same("name with a space (HostFS stores the hard space as U+00A0)", "with space.txt",
         "with\u00a0space.txt", "with space.txt")
    same("name with a colon", "a:b.txt", "a_b.txt")
    same("UPPER.TXT (extension in capitals)", "UPPER.TXT", "UPPER.TXT")
    same("big.dat (3 MB)", "big.dat", "big.dat,ffd", suffix=",ffd")
    same("get -r sub: sub/inner.txt", "sub/inner.txt", "sub/inner.txt")
    same("get -r sub: sub/deep/x.c", "sub/deep/x.c", "sub/deep/x.c")
    same("get hello.txt explicit/name (a name the user chose)", "hello.txt", "explicit.name", "explicit.name,fff")


def check_uploads():
    print("uploads (psftp)")
    up = os.path.join(SF, "up")

    def sent(label, remote, local, *, remote_name=None):
        r = os.path.join(XOUT, remote)
        l = hostfile(up, *local) if isinstance(local, tuple) else os.path.join(up, local)
        if not os.path.exists(r):
            report(label, False, "the server has no %s; has %s" % (remote, sorted(os.listdir(XOUT))))
        elif md5(r) != md5(l):
            report(label, False, "content differs")
        else:
            report(label, True)

    sent("notes/txt -> notes.txt (renamed to renamed.txt)", "renamed.txt", "notes.txt")
    sent("drawing (&AFF) -> drawing,aff", "drawing,aff", "drawing,aff")
    sent("blob/bin (Data) -> blob.bin, no suffix", "blob.bin", "blob.bin,ffd")
    sent("name with a space", "space name.txt", "space name.txt")
    sent("put -r tree: tree/one.txt", "tree/one.txt", "tree/one.txt")
    sent("put -r tree: tree/sub/two.c", "tree/sub/two.c", "tree/sub/two.c")
    sent("put -r tree: a PNG inside (&B60) -> pic,b60", "tree/pic,b60", "tree/pic,b60")
    sent("big/dat 2 MB", "big.dat", "big.dat,ffd")
    sent("put notes/txt madedir/inside.txt", "madedir/inside.txt", "notes.txt")
    if os.path.isdir(os.path.join(XOUT, "madedir")):
        report("mkdir madedir", True)
    else:
        report("mkdir madedir", False, "no directory")


def check_restart():
    print("restarting transfers")
    got = hostfile(os.path.join(SF, "down2"), "big.dat,ffd")
    report("reget finishes a partly fetched file", bool(got) and md5(got) == md5(os.path.join(XIN, "big.dat")),
           "size %s, wanted %s" % (os.path.getsize(got) if got else None, os.path.getsize(os.path.join(XIN, "big.dat"))))
    sent = os.path.join(XFER, "out2", "big.dat")
    report("reput finishes a partly sent file", os.path.exists(sent) and md5(sent) == md5(os.path.join(SF, "up", "big.dat,ffd")),
           "size %s" % (os.path.getsize(sent) if os.path.exists(sent) else None))


