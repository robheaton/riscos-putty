def check_pscp():
    print("pscp")
    pd = os.path.join(SF, "pdown")
    g = hostfile(pd, "got1.txt")
    report("pscp download to a chosen name", bool(g) and md5(g) == md5(os.path.join(XIN, "hello.txt")),
           "missing or different; have %s" % sorted(os.listdir(pd)))
    g = hostfile(pd, "data.bin,ffd")
    report("pscp download into a directory (name mapped, typed Data)",
           bool(g) and md5(g) == md5(os.path.join(XIN, "data.bin")), "have %s" % sorted(os.listdir(pd)))
    g = hostfile(pd, "timed.txt")
    if g:
        report("pscp -p keeps the date", int(os.stat(g).st_mtime) == MTIME,
               "mtime %s, wanted %s" % (int(os.stat(g).st_mtime), MTIME))
    else:
        report("pscp -p keeps the date", False, "file missing")
    g = hostfile(pd, "scp1.txt")
    report("pscp -scp download", bool(g) and md5(g) == md5(os.path.join(XIN, "hello.txt")), "have %s" % sorted(os.listdir(pd)))
    os.makedirs(os.path.join(pd, "scpsub"), exist_ok=True)
    g = hostfile(os.path.join(pd, "scpsub"), "sub/inner.txt", "inner.txt")
    report("pscp -scp -r download", bool(g) and md5(g) == md5(os.path.join(XIN, "sub", "inner.txt")),
           "have %s" % sorted(os.listdir(os.path.join(pd, "scpsub"))))
    r = os.path.join(XOUT, "scpnotes.txt")
    report("pscp -scp upload", os.path.exists(r) and md5(r) == md5(os.path.join(SF, "up", "notes.txt")), "")
    r1, r2 = os.path.join(XOUT, "scptree", "tree", "one.txt"), os.path.join(XOUT, "scptree", "one.txt")
    report("pscp -scp -r upload", os.path.exists(r1) or os.path.exists(r2),
           "have %s" % sorted(os.listdir(os.path.join(XOUT, "scptree"))))
    g = hostfile(pd, "sub/inner.txt")
    report("pscp -r download", bool(g) and md5(g) == md5(os.path.join(XIN, "sub", "inner.txt")), "have %s" % sorted(os.listdir(pd)))
    g = hostfile(pd, "drawing,aff")
    report("pscp download keeps the type from the name (&AFF)", bool(g) and md5(g) == md5(os.path.join(XIN, "drawing,aff")),
           "have %s" % sorted(os.listdir(pd)))
    up = os.path.join(SF, "up")
    r = os.path.join(XOUT, "pnotes.txt")
    report("pscp upload to a chosen name", os.path.exists(r) and md5(r) == md5(os.path.join(up, "notes.txt")), "")
    report("pscp -p upload keeps the date", os.path.exists(r) and int(os.stat(r).st_mtime) == MTIME,
           "mtime %s, wanted %s" % (int(os.stat(r).st_mtime) if os.path.exists(r) else None, MTIME))
    r = os.path.join(XOUT, "drawing,aff")
    report("pscp upload into a directory", os.path.exists(r), "")
    r = os.path.join(XOUT, "ptree", "tree", "one.txt")
    r2 = os.path.join(XOUT, "ptree", "one.txt")
    report("pscp -r upload", os.path.exists(r) or os.path.exists(r2), "have %s" % sorted(os.listdir(os.path.join(XOUT, "ptree"))))
    w = os.path.join(XOUT, "pwild")
    report("pscp upload with a wildcard", os.path.exists(w) and len(os.listdir(w)) >= 1, "have %s" % (os.listdir(w) if os.path.isdir(w) else None))


def parse_log():
    text = open(os.path.join(SF, "log"), "rb").read().decode("latin-1").replace("\r", "")
    import re
    cases = {}
    for chunk in re.split(r"^=== ", text, flags=re.M)[1:]:
        lines = chunk.split("\n")
        name = lines[0].strip()
        rcs = re.findall(r"rc=(\d+) *\n", chunk)
        cases[name] = ("\n".join(lines[1:]), int(rcs[-1]) if rcs else None)
    return cases


def check():
    cases = parse_log()
    files = None
    check_download(files)
    check_uploads()
    check_wildcards()
    check_pscp()
    if "psftp-restart" in cases:
        check_restart()
    print("log summary:")
    for name, (out, rc) in cases.items():
        first = [l for l in out.split("\n") if l.strip() and not l.strip()[0].isdigit()][:3]
        print("  %-26s rc=%s" % (name, rc))
    bad = results.count(False)
    print("\n%d checks, %d failed" % (len(results), bad))
    sys.exit(1 if bad else 0)


def setup():
    make_files()
    build_scripts()
