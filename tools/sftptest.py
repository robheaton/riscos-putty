def make_files():
    """The server's files (what the guest downloads) and the guest's (what it uploads)."""
    shutil.rmtree(XFER, ignore_errors=True)
    shutil.rmtree(SF, ignore_errors=True)
    os.makedirs(XOUT)
    big = os.urandom(3 * 1024 * 1024)
    files = {
        "hello.txt": "hello from the server\nsecond line\n",
        "data.bin": os.urandom(300000),
        "big.dat": big,
        "pic.png": PNG,
        "notes,fff": "a text file whose name says so\n",
        "drawing,aff": bytes([0x44, 0x72, 0x61, 0x77]) + os.urandom(2000),
        "Makefile": "all:\n\techo hi\n",
        "archive.tar.gz": b"\x1f\x8b\x08\x00" + os.urandom(5000),
        "empty.txt": "",
        "weird$&name.txt": "special characters in the name\n",
        "with space.txt": "a space in the name\n",
        "a:b.txt": "a colon in the name\n",
        "UPPER.TXT": "upper case\n",
        "sub/inner.txt": "inside sub\n",
        "sub/deep/x.c": "int main(void) { return 0; }\n",
    }
    for name, data in files.items():
        write(os.path.join(XIN, name), data, MTIME if name == "hello.txt" else None)

    # what the guest uploads: HostFS shows RISC OS "notes/txt" as the host file "notes.txt",
    # and a file of type Data as "name,ffd", a Draw file as "name,aff"
    up = os.path.join(SF, "up")
    write(os.path.join(up, "notes.txt"), "uploaded text\n", MTIME)
    write(os.path.join(up, "drawing,aff"), bytes([0x44, 0x72, 0x61, 0x77]) + os.urandom(1500))
    write(os.path.join(up, "blob.bin,ffd"), os.urandom(70000))
    write(os.path.join(up, "space name.txt"), "a name with a space\n")
    write(os.path.join(up, "big.dat,ffd"), os.urandom(2 * 1024 * 1024))
    write(os.path.join(up, "tree", "one.txt"), "tree one\n")
    write(os.path.join(up, "tree", "sub", "two.c"), "int two;\n")
    write(os.path.join(up, "tree", "pic,b60"), PNG)
    write(os.path.join(SF, "eof"), b"")
    write(os.path.join(SF, "log"), "")
    for d in ("down", "pdown"):
        os.makedirs(os.path.join(SF, d))
    return files


class Script:
    def __init__(self, name):
        self.name = name
        self.lines = ["| generated by tools/sftptest.py - do not edit", "Set Sys$RCLimit 255",
                      "Set Run$Path HostFS::HostFS.$.PuttyDev.,<Run$Path>", "Set PuTTY$Timeout 240",
                      "Dir " + GUEST]

    def run(self, case, cmd):
        log = "{ >> %s.log }" % GUEST
        self.lines += ["Echo === %s %s" % (case, log), "Echo <Sys$Time> %s" % log,
                       "%s < %s.eof %s" % (cmd, GUEST, log), "Echo rc=<Sys$ReturnCode> %s" % log,
                       "Echo <Sys$Time> %s" % log]

    def save(self):
        self.lines.append("Echo script %s finished { >> %s.log }" % (self.name, GUEST))
        write(os.path.join(SF, self.name + ",feb"), "\n".join(self.lines) + "\n")


def opts(extra=""):
    return "-batch -i %s -l tester -P %d -hostkey %s %s" % (USERKEY, PORT, FP, extra)


