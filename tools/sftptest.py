#!/usr/bin/env python3
"""Exercise the RISC OS psftp and pscp (in RPCEmu) against Uppity and compare the results.

Uppity (PuTTY's test server, built for the host) serves SFTP and SCP out of the host's
real file system, so each transfer can be checked from this side: the bytes, the names
(RISC OS leaf <-> Unix name), the filetypes (which show on the host as ",xxx" suffixes on
HostFS files) and the dates.

    tools/sftptest.py setup     make the files on both sides, write the guest scripts and
                                start Uppity on port 2224 (leave it running; Ctrl-C stops it)
    (then in RPCEmu:  Obey HostFS::HostFS.$.PuttyDev.sf.run1, run2, run3, run4)
    tools/sftptest.py check     compare what the guest did with what it should have done

Everything the guest sees is in PuttyDev/sf of the emulator's HostFS (the guest sees
HostFS::HostFS.$.PuttyDev.sf); the server side is build/test/xfer.  HostFS shows a RISC OS
name with the "/" turned into a "." and a filetype other than Text as a ",xxx" suffix, which
is also how the file names the tools make can be checked from here.
"""
